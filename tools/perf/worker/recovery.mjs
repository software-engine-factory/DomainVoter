// Small synthetic correctness exercise, independent of source replica.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createJiti} from 'jiti';
import {accept,start} from './queue.mjs';
const root=path.resolve(import.meta.dirname,'../../..');
const dir=path.join(root,'data/perf-worker/recovery');
fs.mkdirSync(dir,{recursive:true});
for(const suffix of ['', '-wal','-shm'])fs.rmSync(path.join(dir,'voting.db'+suffix),{force:true});
process.env.DATA_DIR=dir;process.env.DV_FREE_MOVE='off';
const jiti=createJiti(import.meta.url,{alias:{'@':path.join(root,'src')},interopDefault:true});
const {getSqlite}=await jiti.import(path.join(root,'src/db/index.ts'));
const db=getSqlite();
db.transaction(()=>{const insert=db.prepare('INSERT INTO pool(name,imported_at) VALUES (?,?)');for(let i=0;i<3000;i++)insert.run(`p${String(i).padStart(5,'0')}.invalid`,Date.now());})();
const input={length:6,cap:3000,chunk:100,pauseMs:1,perRound:1000,rounds:3};
const summary={at:new Date().toISOString(),syntheticRows:3000};
const job=accept(db,input);
summary.admissionRejected=!accept(db,input).accepted;
const stopped=start(db,job.jobId,{stopAfterChunks:32});stopped.done.catch(()=>{});
await new Promise(resolve=>stopped.worker.on('message',m=>{if(m.checkpoint)resolve();}));
const before=db.prepare('SELECT staged,inserted FROM perf_jobs WHERE id=?').get(job.jobId);
assert.deepEqual(before,{staged:3000,inserted:200});
assert.equal(db.prepare("SELECT COUNT(*) n FROM rounds WHERE batch_id=? AND status='open'").get(job.batchId).n,0);
const terminateCode=await stopped.worker.terminate();
await start(db,job.jobId).done;
const after=db.prepare('SELECT status,staged,inserted FROM perf_jobs WHERE id=?').get(job.jobId);
assert.deepEqual(after,{status:'done',staged:3000,inserted:3000});
const sizes=db.prepare('SELECT COUNT(*) n,MIN(position) lo,MAX(position) hi,COUNT(DISTINCT name) uniqueNames FROM domains WHERE round_id IN (SELECT id FROM rounds WHERE batch_id=?) GROUP BY round_id').all(job.batchId);
assert.deepEqual(sizes,Array(3).fill({n:1000,lo:1,hi:1000,uniqueNames:1000}));
summary.restart={terminateCode,before,after,roundSizes:sizes.map(r=>r.n),visibleOnlyWhenComplete:true};
const cancelled=accept(db,input);
const partial=start(db,cancelled.jobId,{stopAfterChunks:32});partial.done.catch(()=>{});
await new Promise(resolve=>partial.worker.on('message',m=>{if(m.checkpoint)resolve();}));
await partial.worker.terminate();
db.prepare('UPDATE perf_jobs SET cancel=1 WHERE id=?').run(cancelled.jobId);
await start(db,cancelled.jobId).done;
assert.equal(db.prepare('SELECT status FROM perf_jobs WHERE id=?').get(cancelled.jobId).status,'cancelled');
assert.equal(db.prepare('SELECT COUNT(*) n FROM round_batch_items WHERE batch_id=?').get(cancelled.batchId).n,0);
assert.equal(db.prepare('SELECT COUNT(*) n FROM rounds WHERE batch_id=?').get(cancelled.batchId).n,0);
summary.cancel={status:'cancelled',remainingBatchItems:0,remainingRounds:0};
const failed=accept(db,input);
await start(db,failed.jobId,{failAfterChunks:32}).done;
assert.equal(db.prepare('SELECT status FROM perf_jobs WHERE id=?').get(failed.jobId).status,'error');
await start(db,failed.jobId).done;
assert.equal(db.prepare('SELECT inserted FROM perf_jobs WHERE id=?').get(failed.jobId).inserted,3000);
summary.failure={injected:true,retryResumed:true,finalCount:3000};
db.close();
fs.writeFileSync(path.join(import.meta.dirname,'result-recovery.json'),JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify(summary));
